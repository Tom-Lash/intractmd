  var STRINGS = { en: EN, es: ES };

  function currentLang() {
    try {
      var v = global.localStorage && global.localStorage.getItem(STORAGE_KEY);
      return v === 'es' ? 'es' : DEFAULT_LANG;
    } catch (e) {
      // Storage can throw in private mode or when site data is blocked.
      return global._uiLang === 'es' ? 'es' : DEFAULT_LANG;
    }
  }

  function interpolate(str, vars) {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, function (whole, name) {
      return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : whole;
    });
  }

  /**
   * Look up a string. Falls back to English, then to the key itself so a typo
   * shows up on screen as the key rather than as an empty space.
   */
  function t(key, vars) {
    var lang = currentLang();
    var k = key;

    if (vars && typeof vars.n === 'number') {
      var plural = k + (Math.abs(vars.n) === 1 ? '_one' : '_other');
      if (STRINGS.en[plural]) k = plural;
    }

    var table = STRINGS[lang] || STRINGS.en;
    var val = table[k];
    if (val === undefined) val = STRINGS.en[k];
    if (val === undefined) return key;
    return interpolate(val, vars);
  }

  /** True when a key has a reviewed translation in the active language. */
  function hasTranslation(key) {
    return currentLang() === 'en' || Object.prototype.hasOwnProperty.call(ES, key);
  }

  function getLang() { return currentLang(); }

  /**
   * Persist the language. Kept deliberately identical to the behaviour the
   * three setLangP/C/D functions had: same storage key, same window._uiLang
   * mirror, so a surface mid-migration and a surface already migrated agree.
   */
  function setLang(lang) {
    var l = lang === 'es' ? 'es' : DEFAULT_LANG;
    try {
      if (global.localStorage) global.localStorage.setItem(STORAGE_KEY, l);
    } catch (e) { /* storage unavailable — fall through to the mirror */ }
    global._uiLang = l;
    return l;
  }

  global.IntractMD = global.IntractMD || {};
  global.IntractMD.i18n = {
    t: t,
    setLang: setLang,
    getLang: getLang,
    hasTranslation: hasTranslation,
    STORAGE_KEY: STORAGE_KEY,
    strings: STRINGS
  };
  global.t = global.t || t;
